-- The part of the API's schema the worker touches (backend migrations
-- 4d0e9b1a8c6f, 5e1f0c2a9b7d, 7b3d5f9a2c4e and f8b0c2d4e6a8). The worker does not own the
-- schema; its integration tests build this copy in their own database. Keep
-- it in step with the backend's models (tasks, task_events, the
-- worker_live_deployments view over deployments).

DROP VIEW IF EXISTS worker_live_deployments;
DROP TABLE IF EXISTS task_events, celery_queue, tasks, deployments CASCADE;
DROP FUNCTION IF EXISTS task_events_notify() CASCADE;
DROP FUNCTION IF EXISTS tasks_drop_job_kwargs() CASCADE;
DROP TYPE IF EXISTS taskstatus, tasktype CASCADE;

CREATE TYPE taskstatus AS ENUM ('PENDING', 'RUNNING', 'SUCCESS', 'FAILED', 'CANCELLED');
CREATE TYPE tasktype AS ENUM ('DEPLOY', 'UPDATE', 'DESTROY', 'PAUSE', 'RESUME', 'REDEPLOY');

CREATE TABLE tasks (
    "taskId"            uuid PRIMARY KEY,
    "deploymentId"      uuid NOT NULL,
    type                tasktype NOT NULL,
    status              taskstatus,
    started_at          timestamp,
    finished_at         timestamp,
    logs                text,
    tf_state            text,
    outputs             text,
    current_phase       varchar(50),
    progress_pct        integer,
    created_at          timestamp DEFAULT timezone('UTC', now()),
    claimed_by          text,
    lease_until         timestamptz,
    cancel_requested_at timestamptz,
    finalized_at        timestamptz,
    outputs_enc         bytea,
    job                 varchar,
    job_kwargs          jsonb
);
CREATE UNIQUE INDEX uq_tasks_active_per_deployment ON tasks ("deploymentId") WHERE status IN ('PENDING', 'RUNNING');

-- A task's job arguments are dropped the moment it leaves PENDING (the claim
-- included), although the worker's role may not write that column.
CREATE OR REPLACE FUNCTION tasks_drop_job_kwargs() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.job_kwargs := NULL;
    RETURN NEW;
END
$$;
CREATE TRIGGER tasks_drop_job_kwargs BEFORE UPDATE OF status ON tasks
    FOR EACH ROW WHEN (NEW.status <> 'PENDING' AND NEW.job_kwargs IS NOT NULL)
    EXECUTE FUNCTION tasks_drop_job_kwargs();

-- Only the columns the view reads.
CREATE TABLE deployments (
    "deploymentId" uuid PRIMARY KEY,
    "appId"        uuid NOT NULL,
    os_project_id  varchar,
    deleted_at     timestamp
);

CREATE VIEW worker_live_deployments AS
SELECT d."deploymentId", d."appId", d.os_project_id
  FROM deployments d
 WHERE d.deleted_at IS NULL
   AND NOT EXISTS (
        SELECT 1 FROM tasks t
         WHERE t."deploymentId" = d."deploymentId"
           AND t.type = 'DESTROY' AND t.status = 'SUCCESS');

CREATE TABLE task_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    uuid NOT NULL REFERENCES tasks ("taskId") ON DELETE CASCADE,
    type       text NOT NULL,
    payload    jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_task_events_task ON task_events (task_id, id);

CREATE FUNCTION task_events_notify() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_notify('task_events', NEW.task_id::text || ':' || NEW.id::text || ':' || NEW.type);
    RETURN NULL;
END
$$;
CREATE TRIGGER task_events_notify AFTER INSERT ON task_events FOR EACH ROW EXECUTE FUNCTION task_events_notify();

-- The worker's role with the grants of migrations 5e1f0c2a9b7d and f8b0c2d4e6a8; the tests
-- in tests/test_job_runtime.py run jobs as this role to prove the worker
-- needs no more than that.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'appstore_worker') THEN
        CREATE ROLE appstore_worker NOLOGIN;
    END IF;
END
$$;
ALTER ROLE appstore_worker LOGIN PASSWORD 'worker-test-password';
GRANT USAGE ON SCHEMA public TO appstore_worker;
GRANT INSERT ON task_events TO appstore_worker;
GRANT SELECT ("taskId", "deploymentId", type, status, claimed_by, lease_until, cancel_requested_at,
              created_at, job, job_kwargs)
   ON tasks TO appstore_worker;
GRANT UPDATE (status, started_at, finished_at, logs, outputs_enc, current_phase, progress_pct,
              claimed_by, lease_until)
   ON tasks TO appstore_worker;
GRANT SELECT ON worker_live_deployments TO appstore_worker;
